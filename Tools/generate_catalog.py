#!/usr/bin/env python3
"""Generate typed Swift and localized labels from the checked-in Apple snapshot.

Pure Python, no installed app, private API, third-party library, or network required.
"""
import csv
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / 'Metadata/Snapshot'
SOURCE = ROOT / 'Sources/SwiftSymbols'
GENERATED = SOURCE / 'Generated'
PLATFORMS = ['iOS', 'macOS', 'tvOS', 'watchOS', 'visionOS']
HEADER = '// Generated by Tools/generate_catalog.py. Do not edit.\n'


def load(name):
    return json.loads((INPUT / (name + '.json')).read_text())


def string(value):
    # JSON string escaping is compatible for these inputs, except Swift interpolation.
    assert '\\(' not in value, 'Unexpected Swift interpolation in input'
    return json.dumps(value, ensure_ascii=False)


def optional(value):
    return 'nil' if value is None else string(value)


def array(values):
    return '[' + ', '.join(string(v) for v in values) + ']'


def property_name(name):
    parts = name.split('.')
    result = parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    if result[0].isdigit():
        result = '_' + result
    assert re.fullmatch('[A-Za-z_][A-Za-z0-9_]*', result), result
    return result


def version_tuple(value):
    parts = tuple(map(int, value.split('.')))
    return parts + (0,) * (3 - len(parts))


def swift_version(value):
    if value is None:
        return 'nil'
    major, minor, patch = version_tuple(value)
    return f'.init(major: {major}, minor: {minor}, patch: {patch})'


def main():
    manifest = load('name_availability')
    names = manifest['symbols']
    # Legacy mappings can point in the opposite direction after a later rename.
    # Preserve that historical file in the snapshot, but use the current alias map.
    aliases = load('name_aliases')
    rows = {r['Name']: r for r in csv.DictReader((INPUT / 'symbols.csv').open(newline=''))}
    suffixes = sorted({r['Name - Locale'] for r in rows.values()} - {''})
    memberships = load('symbol_categories')
    basic = load('symbol_search')
    enhanced = load('enhanced_keywords')
    categories = [c for c in load('categories') if c['key'] not in
                  {'all', 'whatsnew', 'draw', 'variable', 'multicolor'}]
    groups = load('base_symbols_map')
    direct_group = {}
    for key, members in groups.items():
        for member in set([key] + members):
            if member in direct_group:
                raise ValueError(f'Overlapping groups for {member}; review the public grouping contract')
            direct_group[member] = key

    def canonical(name):
        seen = set()
        while name in aliases:
            if name in seen:
                raise ValueError('Alias cycle: ' + name)
            seen.add(name)
            name = aliases[name]
        return name

    def localization(name):
        row = rows.get(name) or rows.get(canonical(name))
        locale = row.get('Name - Locale') if row else None
        if not locale:
            locale = next((s for s in suffixes if name.endswith('.' + s) and
                           name[:-len(s)-1] in names), None)
        if not locale:
            return None, None
        base = name[:-len(locale)-1] if name.endswith('.' + locale) else None
        if base not in names:
            base = None
        return locale, base

    def keys_for(name):
        result = [name, canonical(name)]
        for item in list(result):
            _, base = localization(item)
            if base:
                result += [base, canonical(base)]
        return list(dict.fromkeys(result))

    def versions(name):
        result = dict(manifest['year_to_release'][names[name]])
        # SwiftUI system symbol images are available on macOS 11 and later.
        if result.get('macOS') == '10.15':
            result['macOS'] = '11.0'
        return result

    identifiers = {}
    profiles = []
    restrictions = []
    records = []
    by_release = {}
    for name in sorted(names):
        identifier = property_name(name)
        if identifier in identifiers:
            raise ValueError(f'Swift identifier collision: {name}, {identifiers[identifier]}')
        identifiers[identifier] = name
        keys = keys_for(name)
        current = canonical(name)
        source_row = next((rows[k] for k in keys if k in rows), None)
        introduced = versions(name)
        replacement_versions = versions(current) if current != name and current in names else {}
        profile = []
        for platform in PLATFORMS:
            intro = introduced.get(platform)
            deprecated = replacement_versions.get(platform)
            if not intro or not deprecated or version_tuple(deprecated) <= version_tuple(intro):
                deprecated = None
            profile.append((intro, deprecated))
        if profile not in profiles:
            profiles.append(profile)
        restriction = (source_row or {}).get('Use Restrictions') or None
        if restriction and restriction not in restrictions:
            restrictions.append(restriction)
        terms = []
        for key in keys:
            terms += basic.get(key, []) + enhanced.get(key, [])
            if key in rows:
                for column in ['Search Metadata', 'Functions']:
                    terms += rows[key][column].split(',')
        # Deterministic case-insensitive deduplication, preserving a source spelling.
        unique_terms = {}
        for term in terms:
            term = term.strip()
            if term:
                unique_terms.setdefault(term.casefold(), term)
        category_values = next((memberships[k] for k in keys if k in memberships), [])
        locale, base = localization(name)
        records.append({
            'name': name, 'availabilityIndex': profiles.index(profile),
            'categories': [c['key'] for c in categories if c['key'] in category_values],
            'searchKeywords': [unique_terms[k] for k in sorted(unique_terms)],
            'accessLevel': (source_row or {}).get('Access Level'),
            'restrictionIndex': restrictions.index(restriction) if restriction else None,
            'canonicalName': current if current != name else None,
            'baseLocalizationName': base, 'localization': locale,
            'groupID': next((direct_group[k] for k in keys if k in direct_group), None),
        })
        declaration = f'    /// `{name}`\n'
        if restriction:
            declaration += '    /// - Warning: ' + restriction.replace('\n', ' ') + '\n'
        declaration += '    @available(' + ', '.join(f'{p} {v}' for p, v in introduced.items()) + ', *)\n'
        for platform, (_, deprecated) in zip(PLATFORMS, profile):
            if deprecated:
                declaration += f'    @available({platform}, deprecated: {deprecated}, renamed: "{property_name(current)}")\n'
        declaration += f'    public static var `{identifier}`: SFSymbol {{ .init(rawValue: {string(name)}) }}\n'
        by_release.setdefault(names[name], []).append(declaration)

    # Build output in memory before writing; only generator-owned files are replaced.
    output = {}
    chunks = [records[i:i+128] for i in range(0, len(records), 128)]
    for index, chunk in enumerate(chunks):
        code = HEADER + f'extension GeneratedCatalog {{\n    static func records{index:03d}() -> [SymbolRecord] {{\n        [\n'
        for record in chunk:
            fields = []
            for key, value in record.items():
                if isinstance(value, list): rendered = array(value)
                elif isinstance(value, int): rendered = str(value)
                else: rendered = optional(value)
                fields.append(key + ': ' + rendered)
            code += '            .init(' + ', '.join(fields) + '),\n'
        output[f'Records{index:03d}.swift'] = code + '        ]\n    }\n}\n'
    code = HEADER + 'internal enum GeneratedCatalog {\n'
    code += '    static let records: [SymbolRecord] = [\n' + ''.join(
        f'        records{i:03d}(),\n' for i in range(len(chunks))) + '    ].flatMap { $0 }\n'
    code += '    static let restrictions: [String] = ' + array(restrictions) + '\n'
    code += '    static let localizationSuffixes: [String] = ' + array(suffixes) + '\n'
    code += '    static let availabilities: [SFSymbolAvailability] = [\n'
    for profile in profiles:
        fields = []
        for platform, (intro, deprecated) in zip(PLATFORMS, profile):
            value = 'nil' if intro is None else f'.init(introduced: {swift_version(intro)}, deprecated: {swift_version(deprecated)})'
            fields.append(platform + ': ' + value)
        code += '        .init(' + ', '.join(fields) + '),\n'
    code += '    ]\n    static let categories: [CategoryRecord] = [\n'
    for c in categories:
        code += f'        .init(id: {string(c["key"])}, label: {string(c["label"])}, icon: {string(c["icon"])}),\n'
    code += '    ]\n}\n'
    output['CatalogData.swift'] = code
    # Split groups as well, keeping each generated expression small for the compiler.
    group_rows = []
    for key, variants in sorted(groups.items()):
        members = list(dict.fromkeys(n for n in [key] + variants if n in names))
        group_rows.append(f'            .init(id: {string(key)}, members: {array(members)}),\n')
    group_chunks = [group_rows[i:i+128] for i in range(0, len(group_rows), 128)]
    for index, chunk in enumerate(group_chunks):
        output[f'Groups{index:03d}.swift'] = HEADER + f'extension GeneratedCatalog {{\n    static func groups{index:03d}() -> [GroupRecord] {{\n        [\n' + ''.join(chunk) + '        ]\n    }\n}\n'
    output['Groups.swift'] = HEADER + 'extension GeneratedCatalog {\n    static let groups: [GroupRecord] = [\n' + ''.join(f'        groups{i:03d}(),\n' for i in range(len(group_chunks))) + '    ].flatMap { $0 }\n}\n'
    for release, declarations in by_release.items():
        output['Symbols' + release.replace('.', '_') + '.swift'] = HEADER + 'extension SFSymbol {\n' + ''.join(declarations) + '}\n'
    category_names = {'objectsandtools': 'objectsAndTools', 'cameraandphotos': 'cameraAndPhotos',
                      'privacyandsecurity': 'privacyAndSecurity', 'textformatting': 'textFormatting'}
    output['CategoryMembers.swift'] = HEADER + 'extension SFSymbolCategory {\n' + ''.join(
        f'    public static let {category_names.get(c["key"], c["key"])} = Self(rawValue: {string(c["key"])})\n'
        for c in categories) + '}\n'
    locale_names = {'ar': 'arabic', 'bn': 'bengali', 'el': 'greek', 'gu': 'gujarati', 'he': 'hebrew',
                    'hi': 'hindi', 'ja': 'japanese', 'km': 'khmer', 'kn': 'kannada', 'ko': 'korean',
                    'ml': 'malayalam', 'mni': 'manipuri', 'mr': 'marathi', 'my': 'burmese',
                    'or': 'odia', 'pa': 'punjabi', 'rtl': 'rightToLeft', 'ru': 'russian',
                    'sat': 'santali', 'si': 'sinhala', 'ta': 'tamil', 'te': 'telugu', 'th': 'thai', 'zh': 'chinese'}
    assert set(suffixes) <= locale_names.keys(), 'Review new localization identifiers'
    output['LocalizationMembers.swift'] = HEADER + 'extension SFSymbolLocalization {\n' + ''.join(
        f'    public static let {locale_names[s]} = Self(rawValue: {string(s)})\n' for s in suffixes) + '}\n'
    provenance = load('provenance')
    snapshot_hashes = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(INPUT.iterdir()) if p.is_file()}
    output['Provenance.swift'] = HEADER + '''/// Provenance describes source data independently of the package release tag.
public enum SwiftSymbolsMetadata {
''' + f'    public static let sourceVersion = {string(provenance["sourceVersion"])}\n' + f'    public static let sourceBuild = {string(provenance["sourceBuild"])}\n' + f'    public static let catalogVersion = {string(provenance["sourceVersion"])}\n' + f'    public static let symbolCount = {len(records)}\n' + '    public static let snapshotSHA256: [String: String] = [\n' + ''.join(f'        {string(k)}: {string(v)},\n' for k, v in snapshot_hashes.items()) + '    ]\n}\n'
    GENERATED.mkdir(parents=True, exist_ok=True)
    for old in GENERATED.glob('*.swift'):
        if old.name not in output:
            old.unlink()
    for filename, content in output.items():
        (GENERATED / filename).write_text(content)
    translations = load('category_titles')
    translations.setdefault('en', {})
    resources = SOURCE / 'Resources'
    for old in resources.glob('*.lproj/Categories.strings'):
        if old.parent.stem not in translations:
            old.unlink()
            old.parent.rmdir()
    for language, strings in translations.items():
        folder = resources / (language + '.lproj')
        folder.mkdir(parents=True, exist_ok=True)
        content = '// Generated from Apple CategoryTitles.strings.\n'
        for c in categories:
            content += string('category.' + c['key']) + ' = ' + string(strings.get('sfsymbols-category-' + c['key'], c['label'])) + ';\n'
        (folder / 'Categories.strings').write_text(content)
    print(f'Generated {len(records)} names, {len(groups)} groups, {len(categories)} categories, {len(translations)} localizations, {len(profiles)} availability profiles')


if __name__ == '__main__':
    main()
